#!/usr/bin/env python3
"""Generate ``docs/sdk/python/reference.md``: every public name, one line each.

The page lists what ``import syfthub`` exports, grouped by the module that defines each name,
with its kind and the first line of its docstring. The docstrings themselves are the reference;
this page is the index into them.

Run ``uv run python scripts/gen_api_reference.py`` after changing the public surface.
``tests/unit/test_api_reference.py`` fails until the file on disk matches.
"""

from __future__ import annotations

import enum
import inspect
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import syfthub  # noqa: E402

TARGET = ROOT.parents[1] / "docs" / "sdk" / "python" / "reference.md"

# Section title per defining module, in page order; anything else goes under its module path.
SECTIONS: dict[str, str] = {
    "syfthub.hub": "Client",
    "syfthub._sync": "Client",
    "syfthub.sync": "Client",
    "syfthub.models.session": "Session and options",
    "syfthub.models.sources": "Sources",
    "syfthub.models.search": "Plans and pre-flight",
    "syfthub.models.filters": "Filters",
    "syfthub.models.results": "Results",
    "syfthub.models.money": "Money",
    "syfthub.models.wallets": "Wallets",
    "syfthub.models.enums": "Enums",
    "syfthub.errors": "Errors",
}

# Typing aliases carry no docstring of their own; the module that defines them says what they are.
ALIASES: dict[str, tuple[str, str]] = {
    "Filter": ("syfthub.models.filters", "A ``Condition`` or a ``Group``: anything ``F`` builds."),
}

HEADER = """# API reference

[← Python SDK guide](README.md)

Every name `import syfthub` exports, with the first line of its docstring. The docstrings are the
reference: `help(syfthub.SearchPlan)` prints the full one, with its arguments, return values,
errors and examples. The sync twin's names are the same classes; see `syfthub.sync`.

Generated by `sdk/python/scripts/gen_api_reference.py`; do not edit by hand.
"""


def kind_of(obj: Any) -> str:
    if isinstance(obj, ModuleType):
        return "module"
    if inspect.isclass(obj):
        if issubclass(obj, BaseException):
            return "exception"
        if issubclass(obj, enum.Enum):
            return "enum"
        return "class"
    if inspect.isfunction(obj):
        return "function"
    return "alias"


def summary_of(name: str, obj: Any) -> str:
    if name in ALIASES:
        return ALIASES[name][1]
    doc = inspect.getdoc(obj) or ""
    if isinstance(obj, type) and issubclass(obj, enum.Enum) and doc == inspect.getdoc(enum.Enum):
        doc = ""
    first = doc.strip().splitlines()[0] if doc.strip() else ""
    return first.replace("|", "\\|")


def module_of(name: str, obj: Any) -> str:
    if name in ALIASES:
        return ALIASES[name][0]
    if isinstance(obj, ModuleType):
        return obj.__name__
    return str(getattr(obj, "__module__", "syfthub"))


def generate() -> str:
    rows: dict[str, list[tuple[str, str, str]]] = {}
    for name in sorted(syfthub.__all__):
        if name.startswith("__"):
            continue
        obj = getattr(syfthub, name)
        rows.setdefault(module_of(name, obj), []).append(
            (name, kind_of(obj), summary_of(name, obj))
        )

    out = [HEADER]
    ordered = list(SECTIONS) + sorted(m for m in rows if m not in SECTIONS)
    seen_titles: set[str] = set()
    for module in ordered:
        if module not in rows:
            continue
        title = SECTIONS.get(module, module)
        if title not in seen_titles:
            out.append(f"\n## {title}\n\n| Name | Kind | What it is |\n|---|---|---|\n")
            seen_titles.add(title)
        for name, kind, summary in rows[module]:
            out.append(f"| `syfthub.{name}` | {kind} | {summary} |\n")
    return "".join(out)


def main() -> None:
    TARGET.write_text(generate())
    print(f"wrote {TARGET.relative_to(ROOT.parents[1])}")


if __name__ == "__main__":
    main()
