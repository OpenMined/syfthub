#!/usr/bin/env python3
"""Generate ``docs/api/backend.md`` from the app's routes and OpenAPI schema.

The page lists every route the backend serves, grouped the way the routers are mounted, with its
parameters, request body, responses and auth requirement, followed by every schema those routes
use. Route descriptions come from the handlers' docstrings, so fixing a description means fixing
the docstring.

Run ``uv run python scripts/gen_api_docs.py`` after changing a route or a schema.
``tests/test_api_docs.py`` fails until the file on disk matches.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import TYPE_CHECKING, Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fastapi.routing import APIRoute  # noqa: E402

from syfthub.main import app  # noqa: E402

if TYPE_CHECKING:
    from fastapi.dependencies.models import Dependant

TARGET = ROOT.parents[1] / "docs" / "api" / "backend.md"

JsonDict = dict[str, Any]

ROOT_SECTION = "Root"

# Section title per router tag; a tag not listed here is titled from its name.
TITLES: dict[str, str] = {
    "authentication": "Auth",
    "users": "Users",
    "admin": "Admin",
    "user-aggregators": "User aggregators",
    "endpoints": "Endpoints",
    "collectives": "Collectives",
    "satellites": "Satellites",
    "identity-provider": "Identity provider",
    "nats-peer": "NATS peer tokens",
    "nats": "NATS",
    "feedback": "Feedback",
    "observability": "Observability",
    "wallet": "Wallet",
}

METHODS = ("get", "post", "put", "patch", "delete")

# A docstring section that documents the Python function, not the HTTP route.
DOCSTRING_SECTION = re.compile(
    r"^\s*(Args|Returns|Raises|Yields|Note|Example|Examples):\s*$"
)

CONSTRAINTS: dict[str, str] = {
    "minLength": "min length {}",
    "maxLength": "max length {}",
    "minimum": "min {}",
    "maximum": "max {}",
    "exclusiveMinimum": "more than {}",
    "exclusiveMaximum": "less than {}",
    "minItems": "min {} items",
    "maxItems": "max {} items",
    "pattern": "pattern `{}`",
}

HEADER = """# API reference: backend

Generated by `components/backend/scripts/gen_api_docs.py` from the routes the app serves;
do not edit by hand. To change a description, change the handler's docstring or the schema
field, then regenerate.

- **Base URL (dev):** `http://localhost:8080`
- **Base URL (prod):** `https://{{domain}}`
- **Interactive docs:** `/docs` (Swagger UI) and `/openapi.json` on the same host
- **Routes:** {routes}, in {sections} groups

Paths below are complete: most routes sit under `/api/v1`, a few are at the root.

## Authentication

Send a bearer token in the `Authorization` header:

```http
Authorization: Bearer <token>
```

A route's **Auth** line says what it needs:

| Auth | Meaning |
|---|---|
| Required | A valid token for an active user, or the route answers `401` |
| Optional | Works without a token; a token may widen what the caller sees |
| None | No token is read |

Two kinds of token are accepted wherever auth applies:

- **Hub access token**: a JWT from `POST /api/v1/auth/login`, valid for 30 minutes and renewed
  with `POST /api/v1/auth/refresh`.
- **Personal access token**: a long-lived token starting with `syft_pat_`, created with
  `POST /api/v1/auth/tokens`.

Some routes are further limited to admins or to the owner of the resource; their descriptions
say so. A **satellite token** is a different thing: a 60-second RS256 JWT the Hub mints with
`GET /api/v1/token` for a caller to present to another service (a Space, the aggregator). The
Hub's own routes do not accept it as a login.

## Errors

Errors are JSON with a `detail` member. It is a string for most errors and an object with a
`code` and `message` where a client needs to tell cases apart:

```json
{{"detail": "Endpoint not found"}}
```

```json
{{"detail": {{"code": "VALIDATION_ERROR", "message": "..."}}}}
```

Every route that takes input can also answer `422` with a
[`HTTPValidationError`](#httpvalidationerror) when the input does not match the schema. The
response tables below leave that row out.

## Contents

{contents}
"""


# ---------------------------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------------------------


def anchor(heading: str) -> str:
    """GitHub's anchor for a heading."""
    kept = re.sub(r"[^a-z0-9 _-]", "", heading.lower())
    return kept.replace(" ", "-")


def cell(text: str) -> str:
    """Text made safe for one table cell."""
    flat = " ".join(text.split())
    return flat.replace("|", "\\|")


def prose(text: str) -> str:
    """A docstring as Markdown: function-only sections dropped, RST literals converted."""
    lines: list[str] = []
    for line in text.strip().splitlines():
        if DOCSTRING_SECTION.match(line):
            break
        lines.append(line.rstrip())
    return re.sub(r"``([^`]+)``", r"`\1`", "\n".join(lines).strip())


def first_paragraph(text: str) -> str:
    return prose(text).split("\n\n", 1)[0]


def literal(value: Any) -> str:
    return f"`{json.dumps(value)}`"


# ---------------------------------------------------------------------------------------------
# Schema rendering
# ---------------------------------------------------------------------------------------------


def ref_name(schema: JsonDict) -> str | None:
    ref = schema.get("$ref")
    return ref.rsplit("/", 1)[-1] if isinstance(ref, str) else None


def type_of(schema: JsonDict) -> str:
    """A schema's type in words, linking named schemas."""
    name = ref_name(schema)
    if name is not None:
        return f"[`{name}`](#{anchor(name)})"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            options = list(dict.fromkeys(type_of(option) for option in schema[key]))
            return " or ".join(options)
    if "allOf" in schema:
        return " and ".join(type_of(option) for option in schema["allOf"])
    if "enum" in schema:
        return " or ".join(literal(value) for value in schema["enum"])
    if "const" in schema:
        return literal(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        return (
            f"array of {type_of(items)}"
            if isinstance(items, dict) and items
            else "array"
        )
    if kind == "object":
        extra = schema.get("additionalProperties")
        return (
            f"object of {type_of(extra)}"
            if isinstance(extra, dict) and extra
            else "object"
        )
    if isinstance(kind, str):
        fmt = schema.get("format")
        return f"{kind} ({fmt})" if fmt else kind
    return "any"


def constraints_of(schema: JsonDict) -> list[str]:
    found = [
        text.format(schema[key]) for key, text in CONSTRAINTS.items() if key in schema
    ]
    for key in ("anyOf", "oneOf"):
        for option in schema.get(key, []):
            found.extend(c for c in constraints_of(option) if c not in found)
    return found


def describe(schema: JsonDict, description: str = "") -> str:
    """A field's description followed by its constraints."""
    text = description or schema.get("description", "")
    limits = constraints_of(schema)
    if limits:
        text = (
            f"{text} ({'; '.join(limits)})" if text else "; ".join(limits).capitalize()
        )
    return cell(text)


def default_of(schema: JsonDict) -> str:
    return cell(literal(schema["default"])) if "default" in schema else ""


def schema_section(name: str, schema: JsonDict) -> list[str]:
    out = [f"### {name}", ""]
    if schema.get("description"):
        out += [first_paragraph(schema["description"]), ""]
    if "enum" in schema:
        values = ", ".join(literal(value) for value in schema["enum"])
        return [*out, f"One of: {values}.", ""]
    properties: JsonDict = schema.get("properties", {})
    if not properties:
        return [*out, f"Type: {type_of(schema)}.", ""]
    required = set(schema.get("required", []))
    out += [
        "| Field | Type | Required | Default | Description |",
        "|---|---|---|---|---|",
    ]
    for field, spec in properties.items():
        out.append(
            f"| `{field}` | {cell(type_of(spec))} | {'yes' if field in required else 'no'} "
            f"| {default_of(spec)} | {describe(spec)} |"
        )
    return [*out, ""]


# ---------------------------------------------------------------------------------------------
# Route rendering
# ---------------------------------------------------------------------------------------------


def dependency_names(dependant: Dependant) -> set[str]:
    names: set[str] = set()
    for sub in dependant.dependencies:
        call = sub.call
        if call is not None:
            module = getattr(call, "__module__", "") or ""
            names.add(f"{module}.{getattr(call, '__name__', type(call).__name__)}")
        names |= dependency_names(sub)
    return names


def auth_lines() -> dict[tuple[str, str], str]:
    """Each route's auth requirement, read from the dependencies its handler declares."""
    lines: dict[tuple[str, str], str] = {}
    for route in app.routes:
        if not isinstance(route, APIRoute):
            continue
        names = dependency_names(route.dependant)
        if any(name.endswith(".get_current_active_user") for name in names):
            auth = "Required."
        elif any(name.endswith(".get_optional_current_user") for name in names):
            auth = "Optional."
        else:
            auth = "None."
        if any(".rate_limit." in name for name in names):
            auth += " Rate limited."
        for method in route.methods:
            lines[(method.lower(), route.path)] = auth
    return lines


def body_line(operation: JsonDict) -> str | None:
    body = operation.get("requestBody")
    if not body:
        return None
    parts = [
        f"{type_of(media.get('schema', {}))} as `{kind}`"
        for kind, media in body["content"].items()
    ]
    return f"**Request body:** {' or '.join(parts)}."


def response_body(response: JsonDict) -> str:
    bodies: list[str] = []
    for kind, media in response.get("content", {}).items():
        if "example" in media:
            bodies.append(f"e.g. `{json.dumps(media['example'])}`")
        elif media.get("schema"):
            shape = type_of(media["schema"])
            bodies.append(
                shape if kind == "application/json" else f"{shape} as `{kind}`"
            )
        else:
            bodies.append(f"`{kind}`")
    return cell("; ".join(bodies))


def operation_section(
    method: str, path: str, operation: JsonDict, auth: str
) -> list[str]:
    out = [f"### `{method.upper()} {path}`", ""]
    text = prose(operation.get("description") or operation.get("summary") or "")
    if text:
        out += [text, ""]
    if operation.get("deprecated"):
        out += ["**Deprecated.**", ""]
    out += [f"**Auth:** {auth}", ""]

    parameters: list[JsonDict] = operation.get("parameters", [])
    if parameters:
        out += [
            "| Parameter | In | Type | Required | Default | Description |",
            "|---|---|---|---|---|---|",
        ]
        for parameter in parameters:
            spec: JsonDict = parameter.get("schema", {})
            out.append(
                f"| `{parameter['name']}` | {parameter['in']} | {cell(type_of(spec))} "
                f"| {'yes' if parameter.get('required') else 'no'} | {default_of(spec)} "
                f"| {describe(spec, parameter.get('description', ''))} |"
            )
        out.append("")

    body = body_line(operation)
    if body:
        out += [body, ""]

    out += ["| Status | Meaning | Body |", "|---|---|---|"]
    for status, response in operation["responses"].items():
        if status == "422" and response.get("description") == "Validation Error":
            continue
        out.append(
            f"| `{status}` | {cell(response.get('description', ''))} | {response_body(response)} |"
        )
    return [*out, ""]


def generate() -> str:
    """The whole page as text."""
    spec: JsonDict = app.openapi()
    auth = auth_lines()

    sections: dict[str, list[tuple[str, str, JsonDict]]] = {}
    for path, item in spec["paths"].items():
        for method in METHODS:
            if method in item:
                tags = item[method].get("tags") or [ROOT_SECTION]
                sections.setdefault(tags[0], []).append((method, path, item[method]))

    def title(tag: str) -> str:
        return TITLES.get(tag, tag.replace("-", " ").capitalize())

    ordered = sorted(sections, key=lambda tag: tag != ROOT_SECTION)
    contents = [
        f"- [{title(tag)}](#{anchor(title(tag))}) ({len(sections[tag])})"
        for tag in ordered
    ]
    contents.append("- [Schemas](#schemas)")

    out = [
        HEADER.format(
            routes=sum(len(routes) for routes in sections.values()),
            sections=len(sections),
            contents="\n".join(contents),
        )
    ]
    for tag in ordered:
        out += [f"## {title(tag)}", ""]
        for method, path, operation in sections[tag]:
            out += operation_section(
                method, path, operation, auth.get((method, path), "None.")
            )

    out += ["## Schemas", ""]
    schemas: JsonDict = spec.get("components", {}).get("schemas", {})
    for name in sorted(schemas, key=str.lower):
        out += schema_section(name, schemas[name])
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    TARGET.write_text(generate())
    print(f"wrote {TARGET.relative_to(ROOT.parents[1])}")


if __name__ == "__main__":
    main()
